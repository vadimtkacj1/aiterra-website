const normalize = (value: string) =>
  value
    .toLowerCase()
    .replace(/["'׳״’-]/g, '')
    .replace(/\s+/g, ' ')
    .trim()

export const isTruncatedInRegister = (city: CityName) => city.official.length >= REGISTER_NAME_LIMIT

export const searchCities = (query: string) => {
  const needle = normalize(query)
  if (!needle) return cityNames
  return cityNames.filter((city) =>
    [city.hebrew, city.official, city.common, ...(city.alt ?? [])].some((value) => normalize(value).includes(needle)),
  )
}
