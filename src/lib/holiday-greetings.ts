const toDay = (iso: string) =>
  Date.UTC(Number(iso.slice(0, 4)), Number(iso.slice(5, 7)) - 1, Number(iso.slice(8, 10))) / DAY_MS

const fromDay = (day: number) => new Date(day * DAY_MS).toISOString().slice(0, 10)

export const addDays = (iso: string, days: number) => fromDay(toDay(iso) + days)

const weekdayOf = (iso: string) => new Date(toDay(iso) * DAY_MS).getUTCDay()

const yearOf = (iso: string) => iso.slice(0, 4)

export const formatDate = (iso: string, withYear = true) =>
  `${Number(iso.slice(8, 10))} ב${MONTHS[Number(iso.slice(5, 7)) - 1]}${withYear ? ` ${yearOf(iso)}` : ''}`

const dayName = (iso: string) => {
  const weekday = weekdayOf(iso)
  return weekday === SATURDAY ? 'שבת' : `יום ${WEEKDAYS[weekday]}`
}

const onDay = (iso: string) => {
  const weekday = weekdayOf(iso)
  const prefix = weekday === SATURDAY ? 'בשבת' : `ביום ${WEEKDAYS[weekday]}`
  return `${prefix}, ${formatDate(iso)}`
}

const until = ({ start, end }: Occurrence) => formatDate(end, yearOf(end) !== yearOf(start))

