const SIGN_OFF: Record<AudienceId, Record<ToneId, string>> = {
  clients: { formal: 'בברכה,', warm: 'שלכם,', short: '' },
  employees: { formal: 'בהוקרה,', warm: 'בחום,', short: '' },
  partners: { formal: 'בברכה,', warm: 'בהערכה,', short: '' },
}

export const offerApplies = (audience: AudienceId, offer: string) => audience === 'clients' && offer.trim() !== ''

function signature({ audience, tone, business, sender }: GreetingInput) {
  const company = business.trim()
  const person = sender.trim()
  const organisation = audience === 'employees' && company && !person ? `הנהלת ${company}` : company
  const names = [person, organisation].filter(Boolean)
  if (!names.length) return ''
  const signOff = SIGN_OFF[audience][tone]
  const nameBlock = tone === 'formal' ? names.join('\n') : names.join(', ')
  return signOff ? `${signOff}\n${nameBlock}` : nameBlock
}

export function buildGreetings(input: GreetingInput) {
  const holiday = holidayById(input.holiday)
  const year = input.occurrence ? yearOf(input.occurrence.start) : ''
  const withOffer = offerApplies(input.audience, input.offer)
  const sign = signature(input)

  return greetings[input.holiday][input.audience][input.tone].map((template, index) => {
    const body = template.split('{year}').join(year)
    const decorated = input.emoji ? `${body} ${holiday.emoji[index % holiday.emoji.length]}` : body
    return [
      withOffer ? AD_MARK : '',
      decorated,
      withOffer ? `${holiday.offerLead} ${input.offer.trim()}` : '',
      sign,
      withOffer ? OPT_OUT_LINE : '',
    ]
      .filter(Boolean)
      .join('\n\n')
  })
}

export const combineGreetings = (texts: string[]) =>
  texts.map((text, index) => `ברכה ${index + 1}\n${text}`).join('\n\n\n')
