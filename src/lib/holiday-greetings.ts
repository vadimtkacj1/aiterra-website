const holidayById = (id: HolidayId) => holidays.find((holiday) => holiday.id === id) ?? holidays[0]

export const holidayHeading = (id: HolidayId) => holidayById(id).heading

export function israelToday(now = new Date()) {
  const parts = new Intl.DateTimeFormat('en-US', {
    timeZone: 'Asia/Jerusalem',
    year: 'numeric',
    month: '2-digit',
    day: '2-digit',
  }).formatToParts(now)
  const part = (type: string) => parts.find((item) => item.type === type)?.value ?? ''
  return `${part('year')}-${part('month')}-${part('day')}`
}

function startsFor(id: HolidayId, today: string) {
  if (id !== 'newYear') return STARTS[id]
  const year = Number(yearOf(today))
  return [`${year}-01-01`, `${year + 1}-01-01`]
}

export function nextOccurrence(id: HolidayId, today: string): Occurrence | null {
  const { span } = holidayById(id)
  for (const start of startsFor(id, today)) {
    const end = addDays(start, span)
    if (end >= today) return { start, end }
  }
  return null
}

export function holidayChoices(today: string): HolidayChoice[] {
  return holidays
    .map(({ id, label }) => ({ id, label, occurrence: nextOccurrence(id, today) }))
    .sort((a, b) => {
      if (!a.occurrence) return b.occurrence ? 1 : 0
      if (!b.occurrence) return -1
      return a.occurrence.start.localeCompare(b.occurrence.start)
    })
}

export const defaultHoliday = (today: string) => holidayChoices(today)[0].id

function sendByDate(start: string) {
  const candidate = addDays(start, -SEND_DAYS_BEFORE)
  const weekday = weekdayOf(candidate)
  if (weekday === FRIDAY) return addDays(candidate, -1)
  if (weekday === SATURDAY) return addDays(candidate, -2)
  return candidate
}

export function timingNote(id: HolidayId, occurrence: Occurrence, today: string) {
  const when = holidayById(id).when(occurrence)
  if (id === 'independence') return `${when} שולחים ביום העצמאות עצמו, ולא ביום הזיכרון שלפניו.`
  const sendBy = sendByDate(occurrence.start)
  if (today > sendBy) return `${when} עדיין לא מאוחר: שלחו היום.`
  return `${when} כדאי לשלוח עד ${dayName(sendBy)}, ${formatDate(sendBy, false)}.`
}

