const FINALS: Record<string, string> = { ך: 'כ', ם: 'מ', ן: 'נ', ף: 'פ', ץ: 'צ' }

const unfinal = (stem: string) => {
  const last = stem.slice(-1)
  return stem.slice(0, -1) + (FINALS[last] ?? last)
}

const split = (list: string) => list.split(/\s+/).filter(Boolean)

const withIm = (list: string) =>
  split(list).flatMap((word) => [word, word.endsWith('ה') ? `${word.slice(0, -1)}ים` : `${unfinal(word)}ים`])

const withOt = (list: string) => split(list).flatMap((word) => [word, `${unfinal(word)}ות`])

const withHeOt = (list: string) =>
  split(list).flatMap((word) => (word.endsWith('ה') ? [word, `${word.slice(0, -1)}ות`] : [word]))

const adjectives = (list: string) =>
  split(list).flatMap((word) => [word, `${unfinal(word)}ה`, `${unfinal(word)}ים`, `${unfinal(word)}ות`])

const strongVerbs = (list: string) =>
  split(list).flatMap((word) => {
    if (word.endsWith('ה')) return [word]
    const stem = unfinal(word)
    return [word, `${stem}ה`, `${stem}תי`, `${stem}ת`, `${stem}נו`, `${stem}ו`]
  })

const hiphilVerbs = (list: string) =>
  split(list).flatMap((word) => {
    if (word.at(-2) !== 'י') return [word]
    const full = unfinal(word)
    const short = unfinal(word.slice(0, -2) + word.slice(-1))
    return [word, `${full}ה`, `${short}תי`, `${short}ת`, `${short}נו`, `${full}ו`]
  })

const hehVerbs = (list: string) =>
  split(list).flatMap((word) => {
    const stem = word.slice(0, -1)
    return [word, `${stem}תה`, `${stem}יתי`, `${stem}ית`, `${stem}ינו`, `${stem}ו`]
  })

