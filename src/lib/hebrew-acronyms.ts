export type AcronymMeaning = { text: string; category: AcronymCategoryId }

export type AcronymEntry = {
  display: string
  key: string
  meanings: AcronymMeaning[]
}

const STRIP_MARKS = /[֑-ׇ]/g
const STRIP_QUOTES_KEEP_SPACE = /[״"“”'’׳`’“”.\-־_]/g
const STRIP_QUOTES = /[״"“”'’׳`’“”.\-־_\s]/g

function cleanPhrase(value: string): string {
  return value.replace(STRIP_MARKS, '').replace(STRIP_QUOTES_KEEP_SPACE, '').replace(/\s+/g, ' ').trim()
}

export function normalizeQuery(value: string): string {
  return value.replace(STRIP_MARKS, '').replace(STRIP_QUOTES, '')
}

function buildEntries(): AcronymEntry[] {
  const map = new Map<string, AcronymEntry>()
  for (const line of RAW.split('\n')) {
    const trimmed = line.trim()
    if (!trimmed) continue
    const [display, text, code] = trimmed.split('|')
    const category = categoryByCode[code]
    if (!display || !text || !category) continue
    const key = normalizeQuery(display)
    const meaning = { text: text.trim(), category }
    const existing = map.get(key)
    if (existing) {
      if (!existing.meanings.some((item) => item.text === meaning.text)) existing.meanings.push(meaning)
    } else {
      map.set(key, { display, key, meanings: [meaning] })
    }
  }
  return Array.from(map.values()).sort((a, b) => a.key.localeCompare(b.key, 'he'))
}

export const acronymEntries: AcronymEntry[] = buildEntries()

const PREFIXES = ['ה', 'ב', 'ל', 'מ', 'ו', 'ש', 'כ']

function scoreEntry(entry: AcronymEntry, query: string, phrase: string): number {
  if (entry.key === query) return 0
  if (entry.key.startsWith(query)) return 1
  if (query.length > 2 && PREFIXES.some((prefix) => query.startsWith(prefix) && entry.key === query.slice(1))) return 2
  const matches = entry.meanings.some((item) => {
    const text = cleanPhrase(item.text)
    return text.includes(phrase) || text.split(' ').some((word) => word.startsWith(phrase))
  })
  return matches ? 3 : -1
}

export function searchAcronyms(rawQuery: string, category: AcronymCategoryId | 'all'): AcronymEntry[] {
  const query = normalizeQuery(rawQuery)
  const pool =
    category === 'all'
      ? acronymEntries
      : acronymEntries
          .map((entry) => ({ ...entry, meanings: entry.meanings.filter((item) => item.category === category) }))
          .filter((entry) => entry.meanings.length > 0)
  if (!query) return pool
  return pool
    .map((entry) => ({ entry, score: scoreEntry(entry, query, cleanPhrase(rawQuery)) }))
    .filter((item) => item.score >= 0)
    .sort((a, b) => a.score - b.score)
    .map((item) => item.entry)
}

