export const QUIZ_QUESTION_TOTAL = QUIZ_TOPICS.reduce((sum, topic) => sum + topic.questions.length, 0)

export function pickQuestions(topicIds: string[], count: number, seed: number) {
  const pool = QUIZ_TOPICS.filter((topic) => topicIds.includes(topic.id)).flatMap((topic) => topic.questions)
  return shuffled(pool, seed).slice(0, count)
}

export function quizSections(questions: QuizQuestion[]): SheetSection[] {
  return [
    { title: 'שאלות', items: questions.map(([question]) => question) },
    { title: 'תשובות', items: questions.map(([, answer]) => answer), newPage: true },
  ]
}
