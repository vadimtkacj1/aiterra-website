export type Answers = Record<string, Answer>

export type TraitState = Record<SiteTrait, boolean>

export const defaultTraits = (): TraitState => ({
  forms: false,
  tracking: false,
  newsletter: false,
  storesData: false,
  vendors: false,
})

export const applicableQuestions = (state: TraitState): ChecklistQuestion[] =>
  questions.filter((question) => !question.trait || state[question.trait])

export type Gap = {
  question: ChecklistQuestion
  answer: Answer | null
}

export type Verdict = 'good' | 'gaps' | 'many'

export type ChecklistResult = {
  total: number
  answered: number
  yes: number
  no: number
  unsure: number
  percent: number
  verdict: Verdict
  gaps: Gap[]
  complete: boolean
}

export function evaluate(state: TraitState, answers: Answers): ChecklistResult {
  const list = applicableQuestions(state)
  let earned = 0
  let possible = 0
  let yes = 0
  let no = 0
  let unsure = 0
  const gaps: Gap[] = []
  list.forEach((question) => {
    const answer = answers[question.id] ?? null
    possible += question.weight
    if (answer === 'yes') {
      earned += question.weight
      yes += 1
      return
    }
    if (answer === 'no') no += 1
    if (answer === 'unsure') unsure += 1
    if (answer) gaps.push({ question, answer })
  })
  const rank = (gap: Gap) => (gap.answer === 'no' ? 0 : 1)
  gaps.sort((a, b) => b.question.weight - a.question.weight || rank(a) - rank(b))
  const percent = possible ? Math.round((earned / possible) * 100) : 0
  const answered = yes + no + unsure
  const verdict: Verdict = percent >= 85 ? 'good' : percent >= 60 ? 'gaps' : 'many'
  return { total: list.length, answered, yes, no, unsure, percent, verdict, gaps, complete: answered === list.length }
}

