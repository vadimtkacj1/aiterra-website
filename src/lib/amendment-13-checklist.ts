export const weightLabel: Record<Weight, string> = { 3: 'דחוף', 2: 'חשוב', 1: 'כדאי' }

export function resultToText(result: ChecklistResult): string {
  const lines: string[] = [
    'בדיקת האתר מול תיקון 13 לחוק הגנת הפרטיות',
    `ציון: ${result.percent} מתוך 100 (${verdictText[result.verdict].title})`,
    `${result.yes} במקום, ${result.no} חסרים, ${result.unsure} לא ידועים, מתוך ${result.total} שאלות`,
    '',
  ]
  if (!result.gaps.length) {
    lines.push('לא נמצאו פערים.')
  } else {
    lines.push('מה לתקן:')
    result.gaps.forEach(({ question, answer }, index) => {
      lines.push(
        `${index + 1}. [${weightLabel[question.weight]}] ${question.gap}${answer === 'unsure' ? ' (לא ידוע, צריך לבדוק)' : ''}`,
        `   מה עושים: ${question.fix}`,
        `   על מה זה מבוסס: ${question.basis}`,
      )
    })
  }
  lines.push(
    '',
    'הבדיקה היא כלי עזר כללי ואינה ייעוץ משפטי ואינה קובעת אם האתר עומד בחוק. לבדיקה של המקרה שלכם פנו לעורך דין או ליועץ פרטיות.',
  )
  return lines.join('\n') + '\n'
}
