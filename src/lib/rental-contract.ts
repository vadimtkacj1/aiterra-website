export type RentalInput = {
  landlord: string
  landlordId: string
  tenant: string
  tenantId: string
  address: string
  start: string
  months: number
  rent: number
  deposit: number
  option: boolean
  earlyExit: boolean
}

const MAX_GUARANTEE_MONTHS = 3
const blank = (value: string) => value.trim() || '____________'
const shekels = (value: number) => (value ? `${value.toLocaleString('he-IL')} ₪` : '____ ₪')
const dated = (value: string) => (value ? value.split('-').reverse().join('.') : '____')

export const guaranteeCap = (rent: number, months: number) =>
  Math.min(rent * MAX_GUARANTEE_MONTHS, (rent * months) / 3)

export function rentalContract(input: RentalInput) {
  const { months, rent, deposit } = input
  const sections = [
    `הסכם שכירות למגורים\n\nנערך ונחתם ביום ____\n\nבין: ${blank(input.landlord)}, ת״ז ${blank(input.landlordId)} (להלן: המשכיר)\nלבין: ${blank(input.tenant)}, ת״ז ${blank(input.tenantId)} (להלן: השוכר)`,
    `1. הדירה\nהמשכיר משכיר לשוכר את הדירה ב${blank(input.address)}, למגורים בלבד. תיאור הדירה, מצבה וציודה יפורטו בנספח שייחתם במעמד המסירה.`,
    `2. תקופת השכירות\nתקופת השכירות היא ${months || '____'} חודשים, החל מיום ${dated(input.start)}.`,
    `3. דמי השכירות\nהשוכר ישלם ${shekels(rent)} לחודש, ב-____ לכל חודש, באמצעות ____.`,
    '4. תשלומים\nהשוכר ישא בתשלומים השוטפים בתקופת השכירות: ארנונה, מים, חשמל, גז וועד בית שוטף. המשכיר ישא בהוצאות שהחוק מטיל עליו, ובהן הוצאות הוניות לרכוש המשותף, ביטוח מבנה ודמי תיווך של מתווך שפעל מטעמו.',
    '5. מסירת הדירה\nהמשכיר מצהיר כי הוא רשאי להשכיר את הדירה, וימסור אותה במועד כשהיא ראויה למגורים ונקייה, וללא זכות של צד שלישי הנוגדת את זכויות השוכר.',
    '6. תיקונים\nהשוכר אחראי לליקוי שנגרם משימוש בלתי סביר. המשכיר יתקן על חשבונו ליקוי אחר שאינו קל ערך, בתוך זמן סביר ולא יאוחר מ-30 ימים מקבלת דרישה, ובתיקון דחוף בתוך זמן סביר ולא יאוחר משלושה ימים. השוכר יאפשר למשכיר, בתיאום מראש ובזמן סביר, לבדוק את הדירה ולתקן אותה.',
    `7. ערובה\nלהבטחת חיובי השוכר ימסור השוכר ערובה בסך ${shekels(deposit)} מסוג ____. המשכיר יממש אותה רק במקרים שקובע סעיף 25י לחוק, אחרי הודעה בזמן סביר מראש ואפשרות לתקן, וישיב אותה או את יתרתה בתוך 60 ימים מהשבת הדירה או עד פירעון החובות, לפי המאוחר.`,
    '8. השכרת משנה\nהשוכר לא יעביר את זכויותיו ולא ישכיר את הדירה לאחר בלי הסכמת המשכיר מראש ובכתב.',
  ]
  if (input.option)
    sections.push('9. תקופת הארכה\nלשוכר ברירה להאריך את השכירות ב-____ חודשים, בדמי שכירות של ____ ₪ לחודש. השוכר יודיע על כך לא יאוחר מ-60 ימים לפני תום התקופה. אם הברירה נתונה גם למשכיר, הוא יודיע לא יאוחר מ-90 ימים לפני תום התקופה.')
  if (input.earlyExit)
    sections.push('10. סיום מוקדם\nכל צד רשאי לבטל את ההסכם לפני תום התקופה בעילה הזו: ____. המשכיר יודיע 90 ימים מראש לפחות, והשוכר 60 ימים מראש לפחות.')
  sections.push('פינוי\nבתום השכירות יחזיר השוכר את הדירה נקייה, במצב שבו קיבל אותה, למעט בלאי סביר.')
  sections.push('ולראיה באו הצדדים על החתום. כל צד יקבל העתק חתום.\n\n_______________          _______________\nהמשכיר                         השוכר')
  return sections.join('\n\n')
}
