const onDayName = (dayIndex: number) => (dayIndex === 6 ? 'שבת' : `יום ${DAY_NAMES[dayIndex]}`)

const constraintText = (employee: Employee, shifts: ShiftDef[]) => {
  const parts = employee.off.map((key) => {
    const [day, shiftId] = key.split(':')
    const dayIndex = Number(day)
    const shift = shifts.find((item) => item.id === shiftId)
    return shift ? `${shift.name} ב${onDayName(dayIndex)}` : onDayName(dayIndex)
  })
  if (employee.maxShifts !== 5) parts.push(`עד ${shiftsText(employee.maxShifts)}`)
  return parts.join(', ')
}

const sampleConstraints = sampleSetupData.employees
  .map((employee) => ({ name: employee.name, text: constraintText(employee, sampleSetupData.shifts) }))
  .filter((item) => item.text)

