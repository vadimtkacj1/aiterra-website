function SampleBrief() {
  const blocks = buildBrief(sampleBriefInput(SAMPLE_DATE))
  return (
    <div className={styles.sample} dir="rtl" lang="he">
      {blocks.map((block, index) => {
        if (block.kind === 'title') return <h3 key={index}>{block.text}</h3>
        if (block.kind === 'meta') {
          return (
            <p key={index} className={styles.sampleMeta}>
              {block.items.map((entry, entryIndex) => (
                <Fragment key={entry}>
                  {entryIndex ? ' · ' : ''}
                  <span className={styles.metaItem}>{entry}</span>
                </Fragment>
              ))}
            </p>
          )
        }
        if (block.kind === 'intro') {
          return (
            <p key={index} className={styles.sampleIntro}>
              {block.text}
            </p>
          )
        }
        if (block.kind === 'heading') return <h4 key={index}>{block.text}</h4>
        if (block.kind === 'field') {
          return (
            <p key={index}>
              <strong>{block.label}:</strong> {block.text}
            </p>
          )
        }
        if (block.kind === 'list') {
          return (
            <Fragment key={index}>
              <p className={styles.listLabel}>
                <strong>{block.label}:</strong>
              </p>
              <ul>
                {block.items.map((entry) => (
                  <li key={entry}>{entry}</li>
                ))}
              </ul>
            </Fragment>
          )
        }
        if (block.kind === 'text') return <p key={index}>{block.text}</p>
        return null
      })}
    </div>
  )
}

