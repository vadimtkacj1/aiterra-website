function ServiceTable({ caption, ranks }: { caption: string; ranks: ServiceRank[] }) {
  return (
    <div className={styles.tableWrap} role="region" aria-label={caption} tabIndex={0}>
      <table className={styles.table}>
        <caption>{caption}</caption>
        <thead>
          <tr>
            <th scope="col">דרגה</th>
            <th scope="col">ראשי תיבות</th>
            <th scope="col">מקבילה בצה״ל</th>
            <th scope="col">תפקיד אופייני</th>
          </tr>
        </thead>
        <tbody>
          {ranks.map((rank) => (
            <tr key={rank.name}>
              <th scope="row">{rank.name}</th>
              <td>{rank.abbreviation || '—'}</td>
              <td>{idfNameOf(rank.idfId)}</td>
              <td>{rank.role || '—'}</td>
            </tr>
          ))}
        </tbody>
      </table>
    </div>
  )
}

