function exampleMonth() {
  const entries: Entries = {}
  for (const day of EXAMPLE_DAYS) entries[`2026-11-${String(day).padStart(2, '0')}`] = { start: '08:00', end: '17:00' }
  entries['2026-11-11'] = { start: '08:00', end: '20:00' }
  return buildModel(defaultSettings(2026, 11), entries)
}

