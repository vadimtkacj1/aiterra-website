function SampleStatement() {
  const blocks = buildStatement({ ...sampleStatementInput(SAMPLE_DATE), credit: false })
  return (
    <div className={styles.sample} dir="rtl" lang="he">
      {blocks.map((block, index) => {
        if (block.kind === 'heading') {
          return index === 0 ? <h3 key={index}>{block.text}</h3> : <h4 key={index}>{block.text}</h4>
        }
        if (block.kind === 'paragraph') return <p key={index}>{block.text}</p>
        if (block.kind === 'list') {
          return (
            <ul key={index}>
              {block.items.map((item) => (
                <li key={item}>{item}</li>
              ))}
            </ul>
          )
        }
        return null
      })}
    </div>
  )
}

