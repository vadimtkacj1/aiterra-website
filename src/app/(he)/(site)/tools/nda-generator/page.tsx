function SampleNda() {
  const blocks = buildNda({ ...sampleNdaInput(SAMPLE_DATE), credit: false })
  return (
    <div className={styles.sample} dir="rtl" lang="he">
      {blocks.map((block, index) => {
        if (block.kind === 'title') return <h3 key={index}>{block.text}</h3>
        if (block.kind === 'meta') {
          return (
            <p key={index} className={styles.sampleMeta}>
              {block.text}
            </p>
          )
        }
        if (block.kind === 'party') {
          return (
            <p key={index}>
              <strong>{block.label}</strong> {block.text} (להלן: &quot;{block.alias}&quot;)
            </p>
          )
        }
        if (block.kind === 'recital') return <p key={index}>{block.text}</p>
        if (block.kind === 'lead') {
          return (
            <p key={index} className={styles.lead}>
              {block.text}
            </p>
          )
        }
        if (block.kind === 'heading') return <h4 key={index}>{block.text}</h4>
        if (block.kind === 'clause') {
          return (
            <p key={index}>
              <span className={styles.clauseNo}>{block.number}</span> {block.text}
            </p>
          )
        }
        if (block.kind === 'list') {
          return (
            <ul key={index}>
              {block.items.map((item, itemIndex) => (
                <li key={itemIndex}>{item}</li>
              ))}
            </ul>
          )
        }
        if (block.kind === 'signatures') {
          return (
            <div key={index} className={styles.signatures}>
              <p className={styles.lead}>{block.lead}</p>
              <div className={styles.sigGrid}>
                {block.parties.map((party) => (
                  <div key={party.alias}>
                    <p>
                      <strong>{party.alias}:</strong> {party.name}
                    </p>
                    {party.signatory ? <p>באמצעות: {party.signatory}</p> : null}
                    <p className={styles.sigLine}>
                      {party.stamp ? 'חתימה וחותמת' : 'חתימה'}
                      <span aria-hidden="true" />
                    </p>
                    <p className={styles.sigLine}>
                      תאריך
                      <span aria-hidden="true" />
                    </p>
                  </div>
                ))}
              </div>
            </div>
          )
        }
        return null
      })}
    </div>
  )
}

