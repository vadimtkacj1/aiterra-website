function LightsTable({ level, caption }: { level: LightLevel; caption: string }) {
  return (
    <div className={styles.tableWrap}>
      <table className={styles.table}>
        <caption>{caption}</caption>
        <thead>
          <tr>
            <th scope="col">נורה</th>
            <th scope="col">מה היא אומרת</th>
            <th scope="col">מה עושים</th>
          </tr>
        </thead>
        <tbody>
          {warningLights
            .filter((light) => light.level === level)
            .map((light) => (
              <tr key={light.id}>
                <th scope="row">{light.name}</th>
                <td>{light.meaning}</td>
                <td>{light.action}</td>
              </tr>
            ))}
        </tbody>
      </table>
    </div>
  )
}

