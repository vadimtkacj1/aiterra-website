function SampleInline({ parts }: { parts: PrivacyInline[] }) {
  return (
    <>
      {parts.map((part, index) =>
        typeof part === 'string' ? (
          part
        ) : (
          <a key={index} href={part.href} rel="noopener" target="_blank">
            {part.text}
          </a>
        ),
      )}
    </>
  )
}

function SamplePolicy() {
  const blocks = buildPolicy({ ...samplePrivacyInput(SAMPLE_DATE), credit: false })
  return (
    <div className={styles.sample} dir="rtl" lang="he">
      {blocks.map((block, index) => {
        if (block.kind === 'title') return <h3 key={index}>{block.text}</h3>
        if (block.kind === 'meta') {
          return (
            <p key={index} className={styles.sampleMeta}>
              {block.text}
            </p>
          )
        }
        if (block.kind === 'heading') return <h4 key={index}>{block.text}</h4>
        if (block.kind === 'clause') {
          return (
            <p key={index}>
              <span className={styles.clauseNo}>{block.number}</span> <SampleInline parts={block.parts} />
            </p>
          )
        }
        if (block.kind === 'list') {
          return (
            <ul key={index}>
              {block.items.map((item, itemIndex) => (
                <li key={itemIndex}>
                  <SampleInline parts={item} />
                </li>
              ))}
            </ul>
          )
        }
        return null
      })}
    </div>
  )
}

