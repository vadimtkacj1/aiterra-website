function SampleInline({ parts }: { parts: SpecInline[] }) {
  return (
    <>
      {parts.map((part, index) => (typeof part === 'string' ? part : <span key={index}>{part.text}</span>))}
    </>
  )
}

function SampleSpec() {
  const blocks = buildSpec(sampleSpecInput(SAMPLE_DATE))
  return (
    <div className={styles.sample} dir="rtl" lang="he">
      {blocks.map((block, index) => {
        if (block.kind === 'title') return <h3 key={index}>{block.text}</h3>
        if (block.kind === 'meta') {
          return (
            <p key={index} className={styles.sampleMeta}>
              {block.items.map((item, itemIndex) => (
                <Fragment key={item}>
                  {itemIndex ? ' · ' : ''}
                  <span className={styles.metaItem}>{item}</span>
                </Fragment>
              ))}
            </p>
          )
        }
        if (block.kind === 'intro') {
          return (
            <p key={index} className={styles.sampleIntro}>
              {block.text}
            </p>
          )
        }
        if (block.kind === 'heading') return <h4 key={index}>{block.text}</h4>
        if (block.kind === 'clause') {
          return (
            <p key={index}>
              <span className={styles.clauseNo}>{block.number}</span> <SampleInline parts={block.parts} />
            </p>
          )
        }
        if (block.kind === 'list') {
          return (
            <ul key={index}>
              {block.items.map((item, itemIndex) => (
                <li key={itemIndex}>
                  <SampleInline parts={item} />
                </li>
              ))}
            </ul>
          )
        }
        if (block.kind === 'table') {
          return (
            <table key={index} className={styles.table}>
              <caption className={styles.caption}>העמודים באתר הסטודיו</caption>
              <thead>
                <tr>
                  {block.head.map((cell) => (
                    <th key={cell} scope="col">
                      {cell}
                    </th>
                  ))}
                </tr>
              </thead>
              <tbody>
                {block.rows.map(([no, name, purpose]) => (
                  <tr key={no}>
                    <td>{no}</td>
                    <th scope="row">{name}</th>
                    <td>{purpose}</td>
                  </tr>
                ))}
              </tbody>
            </table>
          )
        }
        return null
      })}
    </div>
  )
}

